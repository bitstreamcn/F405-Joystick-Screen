// 获取 VREFINT 校准值
float Get_Actual_Vref()
{
    uint32_t adc_value_vrefint = 0;

    adc_value_vrefint = adc_values_new[0];

    // 计算实际参考电压 Vref
    float vref_actual = (VREFINT_CALIBRATION_VALUE * 4095.0f) / adc_value_vrefint;

    return vref_actual;
}

void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef* hadc)
{
    if (hadc->Instance == ADC1)  // 判断是哪个ADC
    {
        // 处理DMA传输完成的数据
    	//float vref_actual = Get_Actual_Vref();
    	if (adc_value_flag == 0)
    	{
    		memcpy(adc_values_new, adc_dma_buffer, sizeof(adc_dma_buffer));
    		adc_value_flag = 1;
    	}
    }
}

